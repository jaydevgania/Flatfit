/// Authenticity evaluation category for a flat listing.
enum AuthenticityGrade {
  verifiedAuthentic,
  fairMarketPrice,
  suspiciouslyLow,
  overpriced,
  duplicateRisk,
}

/// Benchmark pricing bracket for a specific locality and room type.
class LocalityPriceBenchmark {
  final String locality;
  final String city;
  final double minRoomRent;
  final double medianRoomRent;
  final double maxRoomRent;

  const LocalityPriceBenchmark({
    required this.locality,
    required this.city,
    required this.minRoomRent,
    required this.medianRoomRent,
    required this.maxRoomRent,
  });
}

/// Report generated by the Listing Authenticity AI engine.
class ListingAuthenticityReport {
  final AuthenticityGrade grade;
  final int trustScore; // 0 - 100
  final double askedRent;
  final double expectedMedianRent;
  final double priceDeviationPercent; // -50% means 50% below median
  final List<String> flaggedAnomalies;
  final List<String> positiveSignals;
  final String aiVerdict;

  const ListingAuthenticityReport({
    required this.grade,
    required this.trustScore,
    required this.askedRent,
    required this.expectedMedianRent,
    required this.priceDeviationPercent,
    required this.flaggedAnomalies,
    required this.positiveSignals,
    required this.aiVerdict,
  });

  bool get isSuspicious =>
      grade == AuthenticityGrade.suspiciouslyLow || grade == AuthenticityGrade.duplicateRisk;
}

/// Pure domain engine for detecting fake, phantom, or suspicious listings in India.
class ListingAuthenticityEngine {
  /// Benchmarks for Mumbai localities (per room / private room in shared flat in INR)
  static final Map<String, LocalityPriceBenchmark> localityBenchmarks = {
    'bandra west': const LocalityPriceBenchmark(
      locality: 'Bandra West',
      city: 'Mumbai',
      minRoomRent: 30000,
      medianRoomRent: 42000,
      maxRoomRent: 70000,
    ),
    'andheri west': const LocalityPriceBenchmark(
      locality: 'Andheri West',
      city: 'Mumbai',
      minRoomRent: 18000,
      medianRoomRent: 26000,
      maxRoomRent: 40000,
    ),
    'powai': const LocalityPriceBenchmark(
      locality: 'Powai',
      city: 'Mumbai',
      minRoomRent: 20000,
      medianRoomRent: 28000,
      maxRoomRent: 45000,
    ),
    'lower parel': const LocalityPriceBenchmark(
      locality: 'Lower Parel',
      city: 'Mumbai',
      minRoomRent: 28000,
      medianRoomRent: 40000,
      maxRoomRent: 65000,
    ),
    'malad west': const LocalityPriceBenchmark(
      locality: 'Malad West',
      city: 'Mumbai',
      minRoomRent: 12000,
      medianRoomRent: 18000,
      maxRoomRent: 28000,
    ),
    'goregaon east': const LocalityPriceBenchmark(
      locality: 'Goregaon East',
      city: 'Mumbai',
      minRoomRent: 14000,
      medianRoomRent: 20000,
      maxRoomRent: 30000,
    ),
    'thane': const LocalityPriceBenchmark(
      locality: 'Thane',
      city: 'Mumbai',
      minRoomRent: 9000,
      medianRoomRent: 14000,
      maxRoomRent: 22000,
    ),
    'navi mumbai': const LocalityPriceBenchmark(
      locality: 'Navi Mumbai',
      city: 'Mumbai',
      minRoomRent: 8000,
      medianRoomRent: 13000,
      maxRoomRent: 20000,
    ),
  };

  /// Fallback benchmark for unspecified Mumbai localities
  static const LocalityPriceBenchmark defaultMumbaiBenchmark = LocalityPriceBenchmark(
    locality: 'Mumbai General',
    city: 'Mumbai',
    minRoomRent: 15000,
    medianRoomRent: 24000,
    maxRoomRent: 45000,
  );

  /// Evaluate authenticity and anomaly signals for a listing.
  static ListingAuthenticityReport evaluateListing({
    required String title,
    required String description,
    required double rent,
    required String locality,
    required int photoCount,
    required bool isVerifiedOwner,
    required bool hasVideoTour,
  }) {
    final anomalies = <String>[];
    final positives = <String>[];
    int score = 70;

    final normalizedLocality = locality.trim().toLowerCase();
    final benchmark = localityBenchmarks.entries
        .firstWhere(
          (entry) => normalizedLocality.contains(entry.key) || entry.key.contains(normalizedLocality),
          orElse: () => MapEntry('default', defaultMumbaiBenchmark),
        )
        .value;

    final median = benchmark.medianRoomRent;
    final deviation = ((rent - median) / median) * 100;

    // Price anomaly evaluation
    if (rent < (benchmark.minRoomRent * 0.55)) {
      // Extremely low rent is the #1 scam indicator in Mumbai real estate
      anomalies.add(
        'Severe Price Anomaly: Rent ₹${rent.toInt()} is >45% below the minimum standard in ${benchmark.locality} (₹${benchmark.minRoomRent.toInt()}). Beware of upfront token requests.',
      );
      score -= 40;
    } else if (rent > (benchmark.maxRoomRent * 1.6)) {
      anomalies.add(
        'Elevated Price: Rent ₹${rent.toInt()} is significantly higher than top market quartile in ${benchmark.locality}.',
      );
      score -= 10;
    } else {
      positives.add('Fair Market Pricing: Rent aligns with verified market data for ${benchmark.locality}.');
      score += 10;
    }

    // Photo & Media evaluation
    if (photoCount == 0) {
      anomalies.add('No photos uploaded. Listings without photos have low authenticity.');
      score -= 25;
    } else if (photoCount >= 4) {
      positives.add('Comprehensive photo documentation ($photoCount photos).');
      score += 10;
    }

    if (hasVideoTour) {
      positives.add('Verified in-app walk-through video tour.');
      score += 15;
    }

    // Verification check
    if (isVerifiedOwner) {
      positives.add('Owner identity & property documents verified by FlatFit.');
      score += 20;
    }

    // Text & description checks
    final text = (title + ' ' + description).toLowerCase();
    if (description.trim().length < 40) {
      anomalies.add('Thin listing description: Lacks essential house rule & amenity details.');
      score -= 10;
    }

    // Check for repetitive duplicate broker spam
    final brokerKeywords = ['urgent client', 'direct deal', 'commission mandatory', 'call directly on'];
    int brokerMatches = 0;
    for (final kw in brokerKeywords) {
      if (text.contains(kw)) brokerMatches++;
    }
    if (brokerMatches >= 2) {
      anomalies.add('Potential duplicate broker syndicate posting.');
      score -= 15;
    }

    if (score > 99) score = 99;
    if (score < 10) score = 10;

    AuthenticityGrade grade;
    String verdict;

    if (rent < (benchmark.minRoomRent * 0.55)) {
      grade = AuthenticityGrade.suspiciouslyLow;
      verdict = 'High Caution: Price appears unrealistically low for this locality. Never pay an advance deposit prior to viewing.';
    } else if (brokerMatches >= 2) {
      grade = AuthenticityGrade.duplicateRisk;
      verdict = 'Review Recommended: Possible duplicated commercial broker posting.';
    } else if (deviation > 60) {
      grade = AuthenticityGrade.overpriced;
      verdict = 'Above Average Rent: Higher than typical listings in this micro-market.';
    } else if (isVerifiedOwner && score >= 85) {
      grade = AuthenticityGrade.verifiedAuthentic;
      verdict = 'High Authenticity: Verified owner documentation with realistic pricing.';
    } else {
      grade = AuthenticityGrade.fairMarketPrice;
      verdict = 'Verified Standard: Realistic rent, adequate details, meets platform standards.';
    }

    return ListingAuthenticityReport(
      grade: grade,
      trustScore: score,
      askedRent: rent,
      expectedMedianRent: median,
      priceDeviationPercent: double.parse(deviation.toStringAsFixed(1)),
      flaggedAnomalies: anomalies,
      positiveSignals: positives,
      aiVerdict: verdict,
    );
  }
}
